"""Record every cubbie line with a warm, natural voice (Kokoro, runs locally, free).

Outputs:
  site/assets/audio/<id>-<clip>.mp3   clip = story | hello | night
  site/voices.js                      clip paths + word start times for the caption highlight

Usage (needs: pip install "kokoro>=0.9.4" soundfile, brew install espeak-ng, ffmpeg):
  python tools/make-voices.py                 # all clips with the chosen voice
  python tools/make-voices.py --samples DIR   # Ganesh lines in several voices, to compare
"""
import glob, json, os, re, subprocess, sys, tempfile

# Kokoro's bundled espeak data path is broken on macOS; use Homebrew's copy.
import espeakng_loader
espeakng_loader.get_data_path = lambda: "/opt/homebrew/share/espeak-ng-data"
espeakng_loader.get_library_path = lambda: sorted(glob.glob("/opt/homebrew/lib/libespeak-ng*.dylib"))[0]

import numpy as np
import soundfile as sf
from kokoro import KPipeline

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SR = 24000

# The cubbie voice: a warm storyteller, slowed a touch and lifted slightly so it sounds young and cute.
VOICE = "af_heart"
SPEED = 0.88
PITCH = 1.12            # 1.12 ≈ two semitones up; tempo is kept the same
PITCH_BY_CUBBIE = {"birbal": 1.06, "tenali": 1.08}   # the clever grown-ups sound a little older

SAMPLE_VOICES = ["af_heart", "af_bella", "af_nicole", "af_sky", "bf_emma", "af_kore"]


def load_cubbies():
    js = "import('./site/cubbies.js').then(m => console.log(JSON.stringify(m.CUBBIES)))"
    out = subprocess.run(["node", "--input-type=module", "-e", js], cwd=ROOT, capture_output=True, text=True, check=True).stdout
    return json.loads(out)


def norm(s):
    return re.sub(r"[^a-z0-9]", "", s.lower())


def speak(pipe, text, voice):
    """Return (audio, [(token_norm, start_seconds), ...])."""
    audio, tokens, offset = [], [], 0.0
    for r in pipe(text, voice=voice, speed=SPEED):
        a = r.audio.numpy()
        for tk in r.tokens or []:
            if tk.start_ts is not None and norm(tk.text):
                tokens.append((norm(tk.text), offset + tk.start_ts))
        audio.append(a)
        offset += len(a) / SR
    return np.concatenate(audio), tokens


def word_starts(text, tokens):
    """Start time for each whitespace-separated word, matching the page's caption."""
    starts, j, last = [], 0, 0.0
    for word in text.split():
        w = norm(word)
        if not w or j >= len(tokens):
            starts.append(round(last, 3))
            continue
        last = tokens[j][1]
        consumed = ""
        while j < len(tokens) and len(consumed) < len(w):
            consumed += tokens[j][0]
            j += 1
        starts.append(round(last, 3))
    return starts


def encode(audio, path, pitch):
    with tempfile.NamedTemporaryFile(suffix=".wav", delete=False) as tmp:
        sf.write(tmp.name, audio, SR)
    chain = f"asetrate={int(SR * pitch)},aresample={SR},atempo={1 / pitch:.5f},loudnorm=I=-16:TP=-1.5:LRA=11"
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", tmp.name, "-af", chain, "-ac", "1", "-c:a", "libmp3lame", "-b:a", "64k", path], check=True)
    os.unlink(tmp.name)


def main():
    pipe = KPipeline(lang_code="a", repo_id="hexgrad/Kokoro-82M")
    cubbies = load_cubbies()

    if "--samples" in sys.argv:
        out = sys.argv[sys.argv.index("--samples") + 1]
        os.makedirs(out, exist_ok=True)
        g = next(c for c in cubbies if c["id"] == "ganesh")
        for v in SAMPLE_VOICES:
            audio, _ = speak(pipe, g["say"] + " " + g["line"], v)
            encode(audio, os.path.join(out, f"ganesh-{v}.mp3"), PITCH)
            print("sample", v)
        return

    os.makedirs(os.path.join(ROOT, "site/assets/audio"), exist_ok=True)
    voices = {}
    for c in cubbies:
        pitch = PITCH_BY_CUBBIE.get(c["id"], PITCH)
        voices[c["id"]] = {}
        for clip, text in (("story", c["line"]), ("hello", c["say"]), ("night", c["night"])):
            audio, tokens = speak(pipe, text, VOICE)
            rel = f"assets/audio/{c['id']}-{clip}.mp3"
            encode(audio, os.path.join(ROOT, "site", rel), pitch)
            entry = {"src": rel}
            if clip == "story":
                entry["words"] = word_starts(text, tokens)
            voices[c["id"]][clip] = entry
            print(c["id"], clip, f"{len(audio) / SR:.1f}s")

    with open(os.path.join(ROOT, "site/voices.js"), "w") as f:
        f.write("// Generated by tools/make-voices.py. Do not edit by hand.\n")
        f.write(f"// Voice: Kokoro {VOICE}, speed {SPEED}, pitch x{PITCH}.\n")
        f.write("export const VOICES = " + json.dumps(voices, indent=1) + ";\n")
    print("wrote site/voices.js")


if __name__ == "__main__":
    main()
